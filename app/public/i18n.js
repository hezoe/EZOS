  function pickLang() {
    let l = window.EZ.lang || localStorage.getItem('ez_lang') || 'ja';
    if (l !== 'ja' && l !== 'en') l = 'ja';
    return l;
  }
  let lang = pickLang();
  window.EZ.lang = lang;
  window.EZ.DICT = DICT; // 参照用(デバッグ/拡張)

  function t(key, vars) {
    const table = DICT[lang] || DICT.ja;
    let s = table[key];
    if (s === undefined) s = DICT.ja[key];
    if (s === undefined) s = key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
    return s;
  }
  window.EZ.t = t;

  // data-i18n 属性を持つ静的要素を埋める
  function applyI18n(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
    scope.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.getAttribute('data-i18n-title')); });
    scope.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
    scope.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  }
  window.EZ.applyI18n = applyI18n;

  // 言語切替: cookie(サーバー描画用) と localStorage に保存し、reload で全面反映
  window.EZ.setLang = function setLang(next) {
    if (next !== 'ja' && next !== 'en') return;
    if (next === lang) return;
    try { localStorage.setItem('ez_lang', next); } catch { /* noop */ }
    document.cookie = `ezlang=${next}; Path=/; Max-Age=31536000; SameSite=Lax`;
    location.reload();
  };

